#!/bin/sh
# examples.sh — regenerate docs/examples/README.md from the binary.
#
# The examples are golden output: CI runs this and fails if the result
# differs from the committed file, so the doc cannot drift from what
# darshini prints (v1.4.1 found it showing a multi-column layout darshini
# cannot produce). Everything shown is deterministic on any machine:
# listings of this checkout show names only, and the long-format example
# runs on a fixture built here with fixed sizes and fixed UTC mtimes and
# no directories (a directory's st_size differs between filesystems).
#
# Usage (from the repository root, after `cyrius build`):
#   tests/examples.sh > docs/examples/README.md
set -eu
export LC_ALL=C
R="$PWD"
B="$R/build/darshini"
[ -x "$B" ] || { echo "examples.sh: build/darshini not built" >&2; exit 1; }
T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT

show() {   # $1 = command as displayed; stdin = its output
    printf '```\n$ %s\n' "$1"
    sed 's/[[:space:]]*$//'
    printf '```\n'
}

# Fixture for the long-format example: a repo whose `notes/` holds one
# file in each git state, with fixed contents and fixed mtimes. The
# mtimes are set BEFORE `git add` so the index records them — darshini
# compares mtime + size, as git's stat check does — and again after the
# edit, which changes the size.
STAMP='2026-01-02 03:04:00 UTC'
mkdir -p "$T/demo/notes"
cd "$T/demo"
git init -q
printf '*.log\n' > .gitignore
printf 'tracked and clean\n' > notes/clean.md
printf 'tracked\n' > notes/edited.txt
printf 'key = "v"\n' > notes/config.toml
for f in notes/*; do touch -d "$STAMP" "$f"; done
git add -A
git -c user.email=ex@ex -c user.name=ex commit -qm demo
printf 'tracked, then edited\n' > notes/edited.txt
printf 'not added\n' > notes/new.rs
printf 'ignored\n' > notes/debug.log
for f in notes/*; do touch -d "$STAMP" "$f"; done
LONG="$("$B" -l --git --mime notes)"
mkdir -p "$T/notrepo"
: > "$T/notrepo/a.txt"; : > "$T/notrepo/b.txt"
cd "$T"
OUTSIDE="$("$B" --git notrepo)"
cd "$R"

cat <<'EOF'
# darshini — example output

Generated by `tests/examples.sh` from the binary at the commit it ships
with, and checked by CI (the doc fails the build if it drifts). On a
terminal, entries also carry color and a Nerd Font glyph; the captures
below use `--no-icons` / `--no-color` where a glyph would not survive
markdown, and say so.

## Default — multi-column on an 80-column TTY

EOF
script -qec "stty cols 80 rows 24 2>/dev/null; $B --no-icons --no-color" /dev/null | tr -d '\r' \
    | show "darshini --no-icons --no-color"
cat <<'EOF'

Vertical-then-horizontal fill, like `ls`. With icons each cell is two
cells wider, so the same listing may fit one column fewer. Dirs render
blue, executables green, symlinks cyan (broken: red).

## Long format with all decoration

EOF
printf '%s\n' "$LONG" | show "darshini -l --git --mime notes"
cat <<'EOF'

Columns: perms / size / mtime (UTC) / mime / git status / name. Status:
`.` tracked and clean, `M` modified, `?` untracked, `!` ignored.

## Tree mode

EOF
"$B" -T --level 2 docs | show "darshini -T --level 2 docs"
cat <<'EOF'

## Multi-path

EOF
"$B" src tests | show "darshini src tests"
cat <<'EOF'

## Classify (`-F`)

EOF
"$B" -F -1 . | head -6 | show "darshini -F -1 . | head -6"
echo
"$B" -dF docs src tests build/darshini | show "darshini -dF docs src tests build/darshini"
cat <<'EOF'

Off the grid, a name with no indicator ends at its last byte — no pad
space (v1.4.1).

## Pipe-aware (script-safe)

EOF
"$B" | head -3 | show "darshini | head -3"
cat <<'EOF'

No color, no icons, no columns — same shape as minimal `ls`.

## Outside a git repo

EOF
printf '%s\n' "$OUTSIDE" | show "darshini --git notrepo"
cat <<'EOF'

`--git` silently skips when there's no `.git/` in the ancestor chain —
no error, no column.
EOF
